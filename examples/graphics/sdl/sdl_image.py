def _line(write, text=""):
    if write: write(text + "\n")
    else: print(text)


async def main(argv=None, cwd="/", read_char=None, write=None):
    s = _image.load_bytes(PNG_BYTES)
    _line(write, "sdl_image: decoded " + str(s.w) + "x" + str(s.h) + " surface")
    # Pixel (0,0) should be rgba(0,0,0,255) → BGRX (0,0,0,255).
    px = list(s.pixels[0:4])
    _line(write, "sdl_image: px(0,0)=" + str(px))
    # Pixel (15,0) is rgba(255,0,255,255) → BGRX (255,0,255,255).
    o = (0*16 + 15) * 4
    px = list(s.pixels[o:o+4])
    _line(write, "sdl_image: px(15,0)=" + str(px))
    _line(write, "sdl_image: ok")
